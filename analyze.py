# ─────────────────────────────────────────────
# Data loading
# ─────────────────────────────────────────────

def load_results_from_pattern(exp_name_pattern, seeds=SEEDS):
    """
    Load metrics.csv for experiments named:
        {exp_name_pattern}_seed{seed}
    """
    dfs = []
    for seed in seeds:
        path = os.path.join(
            RESULTS_DIR,
            f"{exp_name_pattern}_seed{seed}",
            "metrics.csv",
        )
        if os.path.exists(path):
            df = pd.read_csv(path)
            df["seed"] = seed
            dfs.append(df)
        else:
            print(f"  [load] Missing: {path}")

    if not dfs:
        return None
    return pd.concat(dfs, ignore_index=True)


def load_results(model, env, seeds=SEEDS):
    """Standard loader for main benchmark runs: {model}_{env}_seed{seed}"""
    return load_results_from_pattern(f"{model}_{env}", seeds=seeds)


# ─────────────────────────────────────────────
# Metric extraction
# ─────────────────────────────────────────────

def get_final_return_from_pattern(exp_name_pattern, seeds=SEEDS,
                                  last_frac=0.05, last_n_fallback=10):
    """
    Compute mean and std of final returns across seeds.

    Uses the last `last_frac` fraction of each seed's data (default 5%).
    Falls back to `last_n_fallback` rows if the fraction yields fewer rows.
    Returns (mean, std). std is NaN if fewer than 2 seeds have data.
    """
    df = load_results_from_pattern(exp_name_pattern, seeds=seeds)
    if df is None:
        return np.nan, np.nan

    finals = []
    for seed in seeds:
        seed_df = df[df["seed"] == seed]
        if len(seed_df) == 0 or "mean_return" not in seed_df.columns:
            continue

        n_tail = max(
            int(len(seed_df) * last_frac),
            min(last_n_fallback, len(seed_df)),
        )
        tail = seed_df.tail(n_tail)
        finals.append(tail["mean_return"].mean())

    if not finals:
        return np.nan, np.nan

    mean = float(np.mean(finals))
    std = float(np.std(finals)) if len(finals) >= 2 else np.nan
    return mean, std


def get_final_return(model, env, seeds=SEEDS, **kwargs):
    return get_final_return_from_pattern(f"{model}_{env}", seeds=seeds, **kwargs)


def get_mean_omega_from_pattern(exp_name_pattern, seeds=SEEDS,
                                last_frac=0.05, last_n_fallback=10):
    """Compute mean gate value (omega) over the final portion of training."""
    df = load_results_from_pattern(exp_name_pattern, seeds=seeds)
    if df is None:
        return np.nan

    finals = []
    for seed in seeds:
        seed_df = df[df["seed"] == seed]
        if len(seed_df) == 0 or "mean_omega" not in seed_df.columns:
            continue

        n_tail = max(
            int(len(seed_df) * last_frac),
            min(last_n_fallback, len(seed_df)),
        )
        tail = seed_df.tail(n_tail)
        finals.append(tail["mean_omega"].mean())

    return float(np.mean(finals)) if finals else np.nan


def get_mean_omega(model, env, seeds=SEEDS, **kwargs):
    return get_mean_omega_from_pattern(f"{model}_{env}", seeds=seeds, **kwargs)


