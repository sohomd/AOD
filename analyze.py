# Table 1: Main results
# ─────────────────────────────────────────────

def make_results_table():
    print("\n" + "=" * 100)
    print("TABLE 1: Main Results")
    print("=" * 100)

    header = f"{'Model':<25}"
    for env in ENVS:
        header += f"  {env:<20}"
    header += f"  {'Mean ω':<10}"
    print(header)
    print("-" * 100)

    rows = []
    for model in MODELS:
        row = {"model": MODEL_LABELS[model]}
        for env in ENVS:
            mean, std = get_final_return(model, env)
            row[env] = (mean, std)

        # Omega per environment (not just MemoryS7)
        row["mean_omega"] = {}
        for env in ENVS:
            row["mean_omega"][env] = get_mean_omega(model, env)

        rows.append(row)

        # Print table row — report MemoryS7 omega as the canonical value
        line = f"{MODEL_LABELS[model]:<25}"
        for env in ENVS:
            m, s = row[env]
            if np.isnan(m):
                line += f"  {'N/A':<20}"
            elif np.isnan(s):
                line += f"  {m:6.2f} (1 seed)     "
            else:
                line += f"  {m:6.2f} ± {s:4.2f}     "

        omega = row["mean_omega"]["MemoryS7"]
        line += f"  {omega:.3f}" if not np.isnan(omega) else "  N/A"
        print(line)

    print("=" * 100)

    # Export machine-readable summary
    export_summary(rows)
    return rows


def export_summary(rows):
    """Save results as CSV for easy reference in paper writing."""
    records = []
    for row in rows:
        for env in ENVS:
            m, s = row[env]
            records.append({
                "model": row["model"],
                "env": env,
                "mean_return": m,
                "std_return": s,
                "mean_omega": row["mean_omega"][env],
            })
    path = os.path.join(FIGURES_DIR, "summary.csv")
    pd.DataFrame(records).to_csv(path, index=False)
    print(f"Saved: {path}")


